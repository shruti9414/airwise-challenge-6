import { Bot, Sparkles } from 'lucide-react'
import type { Advice } from '../types'
import type { ChatAnswer } from '../lib/ai'
import { AdviceView } from './ui'

export interface Turn {
  id: number
  q: string
  answer?: ChatAnswer
  error?: string
  local?: boolean
}

export interface AdviceResult {
  advice?: Advice
  error?: string
}

const FALLBACK = 'The rule-based advice above remains your fallback.'

function SourceTag({ local }: { local?: boolean }) {
  return local ? (
    <p className="tag">
      <Bot size={16} aria-hidden="true" />
      Rule-based answer · generated on your device, no AI service called
    </p>
  ) : (
    <p className="tag ai-tag">
      <Sparkles size={16} aria-hidden="true" />
      AI-generated by Gemini · checked by AirWise’s safety validator
    </p>
  )
}

/** Chat turns and the optional full AI advice, announced politely to screen readers. */
export default function ChatResults({ turns, result }: { turns: Turn[]; result: AdviceResult | null }) {
  return (
    <div role="status" aria-live="polite">
      {turns.map((t) => (
        <div key={t.id} className={`advice-card chat-turn${t.local ? '' : ' ai'}`}>
          <p className="you">
            <strong>You asked:</strong> {t.q}
          </p>
          {t.answer && (
            <>
              <SourceTag local={t.local} />
              <p>{t.answer.answer}</p>
              {t.answer.steps.length > 0 && (
                <ul className="bullets">
                  {t.answer.steps.map((s) => (
                    <li key={s}>{s}</li>
                  ))}
                </ul>
              )}
            </>
          )}
          {t.error && (
            <p className="notice warn">
              {t.error} {FALLBACK}
            </p>
          )}
        </div>
      ))}
      {result?.error && (
        <p className="notice warn">
          {result.error} {FALLBACK}
        </p>
      )}
      {result?.advice && (
        <div className="advice-card ai">
          <SourceTag />
          <AdviceView advice={result.advice} />
        </div>
      )}
    </div>
  )
}
